const make = (icon, { regularWhenUnfilled = false } = {}) => function FaIcon({ size, style, className, fill }) {
  const filled = fill && fill !== 'none'
  const weight = regularWhenUnfilled && !filled ? 'fa-regular' : 'fa-solid'
  return (
    <i
      className={`${weight} fa-${icon} ${className || ''}`}
      style={{ ...(size ? { fontSize: `${size}px` } : {}), ...style }}
      aria-hidden="true"
    ></i>
  )
}

